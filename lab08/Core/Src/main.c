          // 2. Wait 100 ms (10 Hz transmission rate)
          HAL_Delay(100); 

          // 3. Trigger the next 9-byte SPI reading in the background
          HAL_GPIO_WritePin(GPIOE, GPIO_PIN_3, GPIO_PIN_RESET); 
          HAL_SPI_TransmitReceive_IT(&hspi1, spi_tx_buf, spi_rx_buf, 9);
